def linux_key_mapping():
    from evdev import ecodes

    aliases = {"KEY_PRINTSCREEN": "KEY_SYSRQ", "KEY_CALCULATOR": "KEY_CALC"}
    return {name: getattr(ecodes, aliases.get(name, name)) for name in LINUX_KEY_NAMES}
